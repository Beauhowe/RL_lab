"""Runtime contract consumed by the SuperMimic runner.

Implementations bind a robot, task and simulator. They own simulator readings,
task serialization, observation semantics, rare-event scoring and data drivers.
"""

from typing import Any, Protocol

from .specs import DynamicsSpec, RobotSpec


class RlEnvironment(Protocol):
  """Minimal simulator contract; algorithms need no imagination methods."""

  num_envs: int
  device: Any

  def reset(self) -> tuple[Any, dict]: ...
  def step(self, actions: Any) -> tuple[Any, Any, Any, Any, dict]: ...
  def close(self) -> None: ...


class SuperMimicTaskRuntime(Protocol):
  env: Any
  env_cfg: Any
  robot_spec: RobotSpec
  dynamics: DynamicsSpec
  task_dim: int
  history: int
  terms: tuple[tuple[str, int], ...]
  context: Any
  initial_obs: Any

  def state(self) -> Any: ...
  def pose(self) -> Any: ...
  def pose_delta(self, before: Any, after: Any) -> Any: ...
  def task_state(self) -> Any: ...
  def relief(self, pose: Any) -> Any: ...
  def make_imagination(self, cfg: Any) -> Any: ...
  def driven_actions(self, actions: Any, obs: Any, iteration: int) -> Any: ...
  def on_reset(self, done: Any) -> None: ...
  def seed(self, env_ids: Any, slots: Any, buffer: Any) -> dict: ...
  def rarity(self, windows: dict) -> Any: ...
  def archive_worthy(self, windows: dict) -> Any: ...
  def metrics(self) -> dict: ...
  def log_metrics(self, writer: Any, iteration: int) -> dict[str, float]: ...
  def checkpoint_metadata(self) -> dict: ...
  def checkpoint_terms(self, checkpoint: dict) -> tuple[tuple[str, int], ...]: ...


# Compatibility for existing extensions.
TaskRuntime = SuperMimicTaskRuntime
